def main():
    print("Создание датасета для рекомендательной системы...")
    print(f"Книг в базе: {len(BOOKS)}")

    print("Загрузка нейросети...")
    model = SentenceTransformer("paraphrase-multilingual-MiniLM-L12-v2")

    print("Создание эмбеддингов для книг...")
    descriptions = [book["description"] for book in BOOKS]
    embeddings = model.encode(descriptions, show_progress_bar=True)

    os.makedirs("data", exist_ok=True)

    with open("data/books_metadata.json", "w", encoding="utf-8") as f:
        json.dump(BOOKS, f, ensure_ascii=False, indent=2)

    np.save("data/embeddings.npy", embeddings)

    print(f"Сохранено {len(BOOKS)} книг")
    print("Данные готовы! Запустите API и Flask.")


if __name__ == "__main__":
    main()